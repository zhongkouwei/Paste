const PANEL_HEIGHT = 332;
const helper = path.join(app.getAppPath().replace(/app\.asar$/, 'app.asar.unpacked'), 'native/bin/paste-bridge');

async function native(command, ...args) {
  if (process.platform !== 'darwin' || !fs.existsSync(helper)) return {};
  const { stdout } = await execute(helper, [command, ...args.map(String)], { timeout: 4000, maxBuffer: 2 * 1024 * 1024 });
  return JSON.parse(stdout);
}

function snapshot() { return { ...store.snapshot(), status: { error: lastError, stackMode, stackCount: stack.length } }; }
function emit() {
  for (const window of [mainWindow, settingsWindow]) if (window && !window.isDestroyed()) window.webContents.send('library:changed', snapshot());
}
function report(error) { lastError = error.message; console.error(error); emit(); }

function sourceColor(source) {
  const id = source?.bundleId || '';
  if (/terminal|iterm/i.test(id)) return '#0b252d';
  if (/jetbrains|goland|pycharm/i.test(id)) return '#5bd59b';
  if (/chrome|safari|firefox/i.test(id)) return '#587ce8';
  if (/lark|feishu/i.test(id)) return '#4d79ed';
  if (/code|sublime/i.test(id)) return '#b17ad9';
  return '#77808a';
}

async function currentSource() {
  if (Date.now() - lastSourceAt < 800) return sourceCache;
  const value = await native('frontmost');
  lastSourceAt = Date.now();
  if (value.pid && value.pid !== process.pid && !/paste-easy|pastelike/i.test(value.bundleId || '')) sourceCache = value;
  return sourceCache;
}

function isIgnored(formats, source) {
  const settings = store.data.settings;
  if (settings.paused || settings.excludedApps.includes(source?.bundleId)) return true;
  if (settings.ignoreConfidential && formats.some(f => /concealed|password|confidential/i.test(f))) return true;
  return settings.ignoreTransient && formats.some(f => /transient|autogenerated/i.test(f));
}

async function clipboardSnapshot() {
  const value = await clip.read();
  const { formats, text, html, rtf, files, signature } = value;
  if (!formats.length) return null;
  const source = await currentSource();
  if (isIgnored(formats, source)) return null;
  const metadata = { source: source ? { name: source.name, bundleId: source.bundleId, icon: source.icon, color: sourceColor(source) } : null };
  if (value.image) {
    const original = value.image, image = nativeImage.createFromBuffer(original);
    if (signature === lastSignature) return null;
    const size = image.getSize(), asset = store.putAsset(original);
    return { ...metadata, type: 'image', title: '图片', body: asset, asset, signature, size,
      preview: image.resize({ width: Math.min(480, size.width) }).toDataURL() };
  }
  if (files.length) return { ...metadata, type: 'file', body: files.join('\n'),
    title: decodeURIComponent(files[0].split('/').pop()), preview: files.join('\n'), signature };
  if (!text?.trim() || Buffer.byteLength(text) > 16 * 1024 * 1024) return null;
  return { ...metadata, type: classifyText(text), title: text.split('\n').find(Boolean)?.slice(0, 120) || '文本',
    body: text, html, rtf, preview: text.slice(0, 16000), signature };
}

async function poll() {
  if (polling || store.data.settings.paused) return;
  polling = true;
  try {
    const item = await clipboardSnapshot();
    if (item && item.signature !== lastSignature) { store.add(item); lastSignature = item.signature; lastError = ''; emit(); }
  } catch (error) { report(error); }
  finally { polling = false; }
}

function placePanel() {
  const display = screen.getDisplayNearestPoint(targetApp?.windowPoint || screen.getCursorScreenPoint());
  const { x, y, width, height } = display.bounds;
  mainWindow.setBounds({ x, y: y + height - PANEL_HEIGHT, width, height: PANEL_HEIGHT });
}
async function showPanel(mode) {
  try { const front = await native('frontmost'); if (front.pid && front.pid !== process.pid) targetApp = front; }
  catch (error) { console.error('Could not resolve foreground application', error.message); }
  if (!mainWindow || mainWindow.isDestroyed()) return;
  placePanel(); mainWindow.setVisibleOnAllWorkspaces(true, { visibleOnFullScreen: true });
  mainWindow.show(); mainWindow.moveTop(); mainWindow.focus();
  mainWindow.webContents.send('panel:shown', { target: targetApp?.name || '', mode: mode || 'history' });
}

function createWindow(file, options) {
  const window = new BrowserWindow({ ...options, webPreferences: {
    preload: path.join(__dirname, 'preload.js'), contextIsolation: true, nodeIntegration: false, sandbox: true
  } });
  window.webContents.setWindowOpenHandler(() => ({ action: 'deny' }));
  window.webContents.on('will-navigate', event => event.preventDefault());
  window.webContents.on('will-attach-webview', event => event.preventDefault());
  window.loadFile(path.join(__dirname, file));
  return window;
}
